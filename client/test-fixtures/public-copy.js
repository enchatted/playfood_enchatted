import { readFileSync } from 'node:fs';

const editorialNote = /\b(?:internal (?:note|review|draft)|reviewer(?:'s)? (?:note|comment)|partner design brief|generated by|reviewed by|TODO|FIXME|REQUESTS)\b|\bdocs\//i;
const termsFile = new URL('../../docs/testing/internal-copy-terms.txt', import.meta.url);

function readReviewTerms() {
  try {
    return readFileSync(termsFile, 'utf8').trim().toLowerCase().split(/\r?\n/).filter(Boolean);
  } catch (error) {
    // The standalone source distribution includes only the public editorial checks.
    if (error.code === 'ENOENT') return [];
    throw error;
  }
}

const reviewTerms = readReviewTerms();

export function containsInternalNote(text) {
  const lower = text.toLowerCase();
  return editorialNote.test(text) || reviewTerms.some(term => lower.includes(term));
}
